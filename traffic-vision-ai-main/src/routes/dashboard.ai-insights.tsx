import { createFileRoute } from "@tanstack/react-router";
import { Bot, Sparkles } from "lucide-react";
import { PageHeader, SectionCard } from "@/components/tv/PageHeader";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Progress } from "@/components/ui/progress";
import { useTraffic } from "@/lib/use-traffic";

export const Route = createFileRoute("/dashboard/ai-insights")({ component: AiInsights });

function AiInsights() {
  const { insights, model } = useTraffic();
  return (
    <>
      <PageHeader
        title="AI insights"
        subtitle="Recommendations, risk areas and future traffic trends generated by the prediction engine"
        actions={<Button className="bg-brand text-primary-foreground"><Sparkles className="mr-1.5 h-4 w-4" />Regenerate</Button>}
      />

      <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-3">
        {insights.map((i) => (
          <article key={i.title} className="glass card-hover rounded-2xl p-5">
            <div className="flex items-start justify-between gap-3">
              <span className="bg-brand grid h-10 w-10 place-items-center rounded-xl text-primary-foreground">
                <Bot className="h-5 w-5" />
              </span>
              <Badge variant="outline">{i.impact} impact</Badge>
            </div>
            <h3 className="mt-4 font-display text-base font-bold">{i.title}</h3>
            <p className="mt-1.5 text-sm text-muted-foreground">{i.detail}</p>
            <p className="mt-4 font-display text-xl font-extrabold text-gradient">{i.metric}</p>
          </article>
        ))}
      </div>

      <div className="grid gap-4 lg:grid-cols-2">
        <SectionCard title="Model evaluation" description={`${model.name} · confusion matrix summary`}>
          <ul className="space-y-3">
            {model.confusion.map((c) => (
              <li key={c.label}>
                <div className="flex justify-between text-xs font-semibold">
                  <span>{c.label}</span>
                  <span>TP {c.tp} · FP {c.fp} · FN {c.fn}</span>
                </div>
                <Progress value={(c.tp / (c.tp + c.fp + c.fn)) * 100} className="mt-1 h-2" />
              </li>
            ))}
          </ul>
        </SectionCard>

        <SectionCard title="Risk areas" description="Zones most likely to gridlock in the next 6 hours">
          <ul className="space-y-2 text-sm">
            {["Silk Board Junction", "Hebbal Flyover", "MG Road", "Airport Expressway", "Sarjapur Road"].map((r, i) => (
              <li key={r} className="glass-soft flex items-center justify-between rounded-xl p-3">
                <span className="truncate font-semibold">{r}</span>
                <Badge className={i < 2 ? "bg-destructive/10 text-destructive" : "bg-warning/20 text-warning"}>
                  {92 - i * 9}% risk
                </Badge>
              </li>
            ))}
          </ul>
        </SectionCard>
      </div>
    </>
  );
}
