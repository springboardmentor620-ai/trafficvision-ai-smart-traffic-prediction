"""
AI Traffic Report Router.
"""
from fastapi import APIRouter, Depends
from fastapi.responses import PlainTextResponse
from sqlalchemy.orm import Session

from database import get_db
from services import report_service

router = APIRouter(prefix="/report", tags=["AI Traffic Report"])


@router.get("/ai-report")
def get_ai_report(db: Session = Depends(get_db)):
    """Full AI Traffic Report combining MySQL data + Random Forest predictions."""
    return report_service.generate_ai_report(db)


@router.get("/download", response_class=PlainTextResponse)
def download_text_report(db: Session = Depends(get_db)):
    """Download the AI report as formatted plain text."""
    r = report_service.generate_ai_report(db)

    if "error" in r:
        return r["error"]

    lines = [
        "=" * 70,
        "        TRAFFICVISION AI — INTELLIGENT TRAFFIC MANAGEMENT REPORT",
        "=" * 70,
        f"  Report Date  : {r['report_date']}",
        f"  Report Time  : {r['report_time']}",
        "=" * 70,
        "",
        "── OVERVIEW ──────────────────────────────────────────────────────────",
        f"  Total Locations Monitored  : {r['total_locations_monitored']}",
        f"  Total Vehicles Recorded    : {r['total_vehicles_recorded']}",
        f"  Average Vehicle Count      : {r['average_vehicle_count']}",
        f"  Average Speed              : {r['average_speed_kmh']} km/h",
        "",
        "── CONGESTION ANALYSIS ───────────────────────────────────────────────",
        f"  High Congestion   : {r['high_congestion_count']} locations ({r['high_congestion_percentage']}%)",
        f"  Medium Congestion : {r['medium_congestion_count']} locations",
        f"  Low Congestion    : {r['low_congestion_count']} locations",
        "",
        "── KEY JUNCTIONS ─────────────────────────────────────────────────────",
        f"  Most Congested : {r['most_congested_junction']['location']}",
        f"                   {r['most_congested_junction']['vehicle_count']} vehicles | {r['most_congested_junction']['congestion_level']}",
        f"  Least Congested: {r['least_congested_junction']['location']}",
        f"                   {r['least_congested_junction']['vehicle_count']} vehicles",
        "",
        "── PEAK TRAFFIC ──────────────────────────────────────────────────────",
        f"  Peak Hour      : {r['peak_traffic_hour']}",
        f"  Peak Avg Count : {r['peak_hour_avg_vehicles']} vehicles",
        "",
        "── INCIDENTS ─────────────────────────────────────────────────────────",
        f"  Active Accidents  : {r['accident_count']}",
        f"  Emergency Events  : {r['emergency_count']}",
    ]

    if r["accident_locations"]:
        lines.append(f"  Accident Sites    : {', '.join(r['accident_locations'])}")
    if r["emergency_locations"]:
        lines.append(f"  Emergency Sites   : {', '.join(r['emergency_locations'])}")

    lines += [
        "",
        "── AI PREDICTIONS (RANDOM FOREST — NEXT HOUR) ────────────────────────",
    ]
    for pred in r["rf_predictions_next_hour"]:
        lines.append(
            f"  Junction {pred['junction']} → {pred['predicted_vehicles']} vehicles | "
            f"{pred['congestion_level']} ({pred['urgency']})"
        )

    lines += [
        "",
        "── OVERALL ASSESSMENT ────────────────────────────────────────────────",
        f"  Status  : {r['overall_status']}",
        f"  Action  : {r['overall_action_required']}",
        "",
        "── AI RECOMMENDATIONS ────────────────────────────────────────────────",
    ]
    for i, rec in enumerate(r["ai_recommendations"], 1):
        lines.append(f"  {i}. {rec}")

    lines += [
        "",
        "=" * 70,
        "  Generated by TrafficVision AI — Powered by Random Forest ML",
        "=" * 70,
    ]

    return "\n".join(lines)
