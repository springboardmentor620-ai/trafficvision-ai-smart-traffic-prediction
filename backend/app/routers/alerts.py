from typing import Optional
from pydantic import BaseModel, EmailStr
from fastapi import APIRouter, Depends, Body
from sqlalchemy.orm import Session

from app.database.connection import get_db
from app.schemas.alert import AlertResponse
from app.services.alert_service import AlertService
from app.services.email_service import EmailService

router = APIRouter(
    prefix="/alerts",
    tags=["Alerts"],
)


class TestSmtpRequest(BaseModel):
    recipient: Optional[str] = "admin@trafficvision.ai"
    road: Optional[str] = "Outer Ring Road (Silk Board Junction)"
    severity: Optional[str] = "Critical"
    message: Optional[str] = "Test Emergency Incident Dispatch generated by Municipal Admin Console."


@router.get(
    "",
    response_model=list[AlertResponse],
)
def get_alerts(
    db: Session = Depends(get_db),
):
    return AlertService.get_alerts(db)


@router.put("/{alert_id}/resolve")
def resolve_alert(
    alert_id: int,
    db: Session = Depends(get_db),
):
    alert = AlertService.resolve_alert(
        db,
        alert_id,
    )

    if not alert:
        return {
            "message": "Alert not found"
        }

    return alert


@router.post("/test-smtp")
def test_smtp_dispatch(
    payload: TestSmtpRequest = Body(default_factory=TestSmtpRequest),
):
    """
    Sends a test alert email via SMTP or simulated dispatch to verify
    email notification infrastructure.
    """
    result = EmailService.send_alert_email(
        title="[TEST DISPATCH] Critical Congestion Telemetry Simulation",
        message=payload.message or "High vehicle volume surge detected across junction. Dynamic bypass reroute active.",
        severity=payload.severity or "Critical",
        road=payload.road or "Outer Ring Road (Silk Board)",
        alert_type="Incident",
        recipients=[payload.recipient] if payload.recipient else None,
    )
    return {
        "status": "success",
        "dispatch_details": result,
        "message": "SMTP alert email dispatch triggered successfully.",
    }